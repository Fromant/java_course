package inheritance_polymorphism.static_override;

// Статические методы связаны с классом, а не с экземпляром.
// Они разрешаются на этапе компиляции на основе статического типа ссылки,
// а не реального типа объекта. Поэтому динамический полиморфизм невозможен.

class A {
    public static void method() {
        System.out.println("Статический метод из класса A");
    }
}

class B extends A {
    // Попытка "переопределить" статический метод на самом деле является сокрытием (hiding)
    // Аннотация @Override здесь недопустима и вызовет ошибку компиляции.
    // Компилятор не позволяет использовать @Override для статических методов.

    // @Override // Эта строка вызовет ОШИБКУ: "Static methods cannot be overridden"
    public static void method() {
        System.out.println("Статический метод из класса B");
    }
}

public class Practice1_StaticPolymorphism {
    public static void main(String[] args) {
        A obj1 = new A();
        A obj2 = new B(); // ссылка типа A, объект типа B

        // Вызов статического метода — разрешается по типу ССЫЛКИ (A), а не по типу ОБЪЕКТА (B)
        obj1.method(); // Вывод: "Статический метод из класса A"
        obj2.method(); // Вывод: "Статический метод из класса A" — НЕ из B!

        // Чтобы вызвать метод из B, нужно использовать имя класса B напрямую:
        B.method(); // Вывод: "Статический метод из класса B"

        // Вывод: связывание статических методов — статическое (на этапе компиляции),
        // а не динамическое (во время выполнения). Поэтому полиморфизм не работает.
    }
}
