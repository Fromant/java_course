package strings.stringClass;

public class Practice3_TextBlocks {

    public static void main(String[] args) {
        // Начиная с Java 15 появились текстовые блоки —
        // многострочные строковые литералы, записываемые в тройных кавычках: """

        // Пример 1: многострочный текст без конкатенации
        String json = """
        {
            "name": "Иван",
            "age": 30,
            "city": "Москва"
        }
        """;
        System.out.println("JSON:\n" + json);

        // Пример 2: удобство форматирования HTML или SQL
        String html = """
        <html>
            <body>
                <h1>Привет, мир!</h1>
            </body>
        </html>
        """;
        System.out.println("HTML:\n" + html);

        // Преимущества тройных кавычек:
        // - Не нужно экранировать кавычки внутри (только тройные)
        // - Сохраняется форматирование (с возможностью контроля через .stripIndent())
        // - Автоматически вставляются символы перевода строки
        // - Упрощает работу с многострочными константами
    }
}
