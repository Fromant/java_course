package exceptions.hierarchy;

// Иерархия исключений в Java и назначение основных классов

public class Practice1_ExceptionHierarchy {
    public static void main(String[] args) {
        // Throwable - корень всей иерархии исключений.
        // Только его подклассы могут быть "выброшены" (throw) и "пойманы" (catch).

        // Error - указывает на серьёзные системные ошибки, которые обычно
        // не подлежат обработке в прикладной программе.
        // Примеры: OutOfMemoryError, StackOverflowError.
        // Программист не обязан и часто не может их обрабатывать.

        // Exception - корень для всех исключений, которые могут и должны
        // обрабатываться в нормальных условиях работы программы.
        // Делится на два вида:
        //   1. Проверяемые исключения (checked exceptions) - наследники Exception,
        //      кроме RuntimeException.
        //      Компилятор требует их обрабатывать или объявлять в throws.
        //      Пример: IOException, SQLException.
        //
        //   2. Непроверяемые исключения (unchecked exceptions) - наследники RuntimeException.
        //      Компилятор не требует их обработки.
        //      Обычно возникают из-за ошибок программиста: деление на ноль, null и т.д.

        // RuntimeException - базовый класс для всех непроверяемых исключений.
        // Используется для ошибок времени выполнения, вызванных логическими ошибками в коде.
    }
}
